#!/bin/bash
# Запуск всего ресторана на одном компьютере в одном окне терминала.
# Повара, официанты, вход и наблюдатель стартуют в фоне (их вывод — в папке logs/)
# и ждут сервер; сервер работает в этом окне: здесь вводятся параметры и нажимается Ctrl+C.
# Использование: ./run_all.sh [порт] [поваров] [официантов]   (по умолчанию 5000, 4 и 3)
# Посмотреть на ресторан целиком можно из другого окна: ./observer 127.0.0.1 5000
# или: tail -f logs/observer.log

cd "$(dirname "$0")" || exit 1
PORT=${1:-5000}
COOKS=${2:-4}
WAITERS=${3:-3}

mkdir -p logs
for i in $(seq "$COOKS"); do ./cook 127.0.0.1 "$PORT" > logs/cook$i.log 2>&1 & done
for i in $(seq "$WAITERS"); do ./waiter 127.0.0.1 "$PORT" > logs/waiter$i.log 2>&1 & done
./observer 127.0.0.1 "$PORT" > logs/observer.log 2>&1 &
./door 127.0.0.1 "$PORT" > logs/door.log 2>&1 &
./server "$PORT"        # сервер — в этом окне (параметры можно и из файла: ./run_all.sh 5000 4 3 < файл)
wait                    # когда сервер закончит, клиенты получат BYE и тоже закончат
